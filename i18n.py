def tr(lang: str, key: str, **kwargs) -> str:
    table = TRANSLATIONS.get(lang, TRANSLATIONS["es"])
    text = table.get(key, TRANSLATIONS["es"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def translate_engine_phase(lang: str, raw_phase: str) -> str:
    """Translate internal ClickerEngine / MacroPlayer phase tokens to display language."""
    if raw_phase == "DETENIDO":
        return tr(lang, "phase_stopped")
    if raw_phase == "CUENTA REGRESIVA":
        return tr(lang, "phase_countdown")
    if raw_phase == "PAUSADO (VENTANA)":
        return tr(lang, "phase_paused_win")
    if raw_phase == "MANTENIENDO":
        return tr(lang, "phase_holding")
    if raw_phase == "MANTENIENDO (∞)":
        return tr(lang, "phase_holding_inf")
    if raw_phase == "MANTENIENDO ZONA (∞)":
        return tr(lang, "phase_holding_zone_inf")
    if raw_phase == "MANTENIENDO (REAL)":
        return tr(lang, "phase_holding_real")
    if raw_phase == "MANTENIENDO (ZONA)":
        return tr(lang, "phase_holding_zone")
    if raw_phase.startswith("MANTENIENDO ZONA #"):
        num = raw_phase.split("#", 1)[1]
        return tr(lang, "phase_holding_zone_n", n=num)
    if raw_phase == "ESPERANDO":
        return tr(lang, "phase_waiting")
    if raw_phase == "CLICKEANDO":
        return tr(lang, "phase_clicking")
    if raw_phase == "LISTO":
        return tr(lang, "phase_ready")
    if raw_phase == "REPRODUCIENDO":
        return tr(lang, "phase_playing")
